// 目的地名（部分マッチも含む）→ 座標と国内/海外分類を返す
export function getCoordsForDestination(dest: string): { coord: Coord; isOverseas: boolean } | null {
    if (DOMESTIC_COORDS[dest]) return { coord: DOMESTIC_COORDS[dest], isOverseas: false }
    if (OVERSEAS_COORDS[dest]) return { coord: OVERSEAS_COORDS[dest], isOverseas: true }

    // 最長一致探索（複数都市名を含むタイトルの場合、最初に見つかる代表都市の座標を採用）
    let bestKey = ''
    let bestCoord: Coord | null = null
    let bestIsOverseas = false

    for (const [key, coord] of Object.entries(DOMESTIC_COORDS)) {
        if (dest.includes(key) && key.length > bestKey.length) {
            bestKey = key
            bestCoord = coord
            bestIsOverseas = false
        }
    }
    for (const [key, coord] of Object.entries(OVERSEAS_COORDS)) {
        if (dest.includes(key) && key.length > bestKey.length) {
            bestKey = key
            bestCoord = coord
            bestIsOverseas = true
        }
    }

    if (bestCoord) return { coord: bestCoord, isOverseas: bestIsOverseas }
    return null
}
